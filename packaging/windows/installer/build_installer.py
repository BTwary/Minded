"""Build Native Windows Installer Setup (MindedSetup.exe) for Minded AA-OS.

Compiles native C# launcher, uninstaller, and setup wizard using Windows csc.exe,
embeds the complete offline application payload, and outputs a standalone MindedSetup.exe.
"""
from __future__ import annotations

import os
import re
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

REPO_ROOT = Path(__file__).resolve().parents[3]
INSTALLER_DIR = Path(__file__).resolve().parent
CSC_COMPILER = Path(r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe")
DOWNLOADS_DIR = Path(os.path.expanduser("~/Downloads"))

EXCLUDE_DIRS = {
    ".git",
    "__pycache__",
    ".pytest_cache",
    ".venv",
    "venv",
    "node_modules",
    ".next",
    "dist",
    "build",
    "data_store",
    "tests",
}

EXCLUDE_EXTS = {
    ".pyc",
    ".pyo",
    ".pyd",
    ".db",
    ".sqlite",
    ".sqlite3",
    ".pkl",
    ".zip",
    ".log",
    ".tmp",
}


def read_release_version() -> str:
    """Single authoritative release version: ``minded.__version__``."""
    text = (REPO_ROOT / "minded" / "__init__.py").read_text(encoding="utf-8")
    m = re.search(r"^__version__\s*=\s*[\"']([0-9]+(?:\.[0-9]+){1,3})[\"']", text, re.MULTILINE)
    if not m:
        raise RuntimeError("minded/__init__.py must define a numeric __version__ for the installer")
    return m.group(1)


def write_release_info(target: Path) -> Path:
    target.write_text(
        "// Generated by build_installer.py from minded.__version__ -- do not edit.\n"
        "namespace Minded.Installer\n{\n"
        "    internal static class ReleaseInfo\n    {\n"
        f'        public const string Version = "{read_release_version()}";\n'
        "    }\n}\n",
        encoding="utf-8",
    )
    return target


def compile_csharp(source_file: Path, output_file: Path, references: list[str] | None = None,
                   resources: list[tuple[Path, str]] | None = None,
                   extra_sources: list[Path] | None = None) -> None:
    if not CSC_COMPILER.is_file():
        raise RuntimeError(f"C# compiler not found at {CSC_COMPILER}")

    cmd = [
        str(CSC_COMPILER),
        "/nologo",
        "/target:winexe",
        f"/out:{output_file}",
    ]

    for ref in references or []:
        cmd.append(f"/r:{ref}")

    for res_path, res_name in resources or []:
        cmd.append(f"/resource:{res_path},{res_name}")

    cmd.append(str(source_file))
    cmd.extend(str(extra) for extra in extra_sources or [])

    print(f"Compiling {source_file.name} -> {output_file.name}...")
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"Compilation of {source_file.name} failed:\n{res.stderr or res.stdout}")
    print(f" -> Successfully compiled {output_file.name}")


def create_payload_zip(target_zip: Path) -> int:
    """Package the built desktop application with paths relative to its bundle."""
    bundle_dir = (
        REPO_ROOT
        / "packaging"
        / "windows"
        / "bundle"
        / "MindedAAOS"
    )

    required = [
        bundle_dir / "MindedAAOS.exe",
        bundle_dir / "_internal",
        bundle_dir / "frontend" / "index.html",
        bundle_dir / "OFFLINE_MODE",
    ]

    missing = [str(p) for p in required if not p.exists()]
    if missing:
        raise RuntimeError(
            "Desktop bundle is incomplete:\n" + "\n".join(missing)
        )

    target_zip.parent.mkdir(parents=True, exist_ok=True)
    file_count = 0

    with zipfile.ZipFile(
        target_zip,
        "w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=3,
    ) as archive:
        for path in sorted(bundle_dir.rglob("*")):
            if not path.is_file():
                continue

            # Critical: files must be rooted at the app directory,
            # not at the repository root.
            relative_name = path.relative_to(bundle_dir).as_posix()
            archive.write(path, arcname=relative_name)
            file_count += 1

    if file_count == 0:
        raise RuntimeError("Application payload is empty.")

    with zipfile.ZipFile(target_zip, "r") as archive:
        names = set(archive.namelist())

    for required_name in (
        "MindedAAOS.exe",
        "frontend/index.html",
        "OFFLINE_MODE",
    ):
        if required_name not in names:
            raise RuntimeError(
                f"Required file missing from payload: {required_name}"
            )

    if not any(name.startswith("_internal/") for name in names):
        raise RuntimeError("PyInstaller _internal payload is missing.")

    print(
        f"Application payload created: {file_count} files, "
        f"{target_zip.stat().st_size / (1024 * 1024):.1f} MiB"
    )
    print("Payload root verified: MindedAAOS.exe")

    return file_count



def build_installer() -> Path:
    print("=" * 70)
    print("BUILDING MINDED ENTERPRISE DESKTOP INSTALLER (MindedSetup.exe)")
    print("=" * 70)

    launcher_cs = INSTALLER_DIR / "MindedLauncher.cs"
    launcher_exe = INSTALLER_DIR / "Minded.exe"
    uninstaller_cs = INSTALLER_DIR / "MindedUninstall.cs"
    uninstaller_exe = INSTALLER_DIR / "Uninstall.exe"
    setup_cs = INSTALLER_DIR / "MindedSetup.cs"
    setup_exe = INSTALLER_DIR / "MindedSetup.exe"
    payload_zip = INSTALLER_DIR / "payload.zip"

    webview2_installer = (
        REPO_ROOT
        / "packaging"
        / "windows"
        / "redistributables"
        / "MicrosoftEdgeWebView2RuntimeInstallerX64.exe"
    )

    if not webview2_installer.is_file():
        raise RuntimeError(
            f"WebView2 offline installer missing: {webview2_installer}"
        )

    if webview2_installer.stat().st_size < 100 * 1024 * 1024:
        raise RuntimeError(
            "WebView2 installer is unexpectedly small; "
            "the full offline installer is required."
        )

    # 1. Compile the launcher.
    compile_csharp(launcher_cs, launcher_exe)

    # 2. Compile the uninstaller.
    compile_csharp(uninstaller_cs, uninstaller_exe)

    # 3. Create and validate the application payload.
    create_payload_zip(payload_zip)

    release_info_cs = write_release_info(
        INSTALLER_DIR / "ReleaseVersion.g.cs"
    )

    # 4. Build setup with each resource embedded exactly once.
    compile_csharp(
        setup_cs,
        setup_exe,
        extra_sources=[release_info_cs],
        references=[
            "System.IO.Compression.dll",
            "System.IO.Compression.FileSystem.dll",
            "Microsoft.CSharp.dll",
        ],
        resources=[
            (payload_zip, "payload.zip"),
            (launcher_exe, "Minded.exe"),
            (uninstaller_exe, "Uninstall.exe"),
            (
                webview2_installer,
                "MicrosoftEdgeWebView2RuntimeInstallerX64.exe",
            ),
        ],
    )

    setup_size_mb = setup_exe.stat().st_size / (1024 * 1024)
    print(
        f"\n[OK] Standalone installer generated: "
        f"{setup_exe.name} ({setup_size_mb:.2f} MB)"
    )

    # 5. Copy the installer to the distribution locations.
    destinations = [
        DOWNLOADS_DIR / "MindedSetup.exe",
        REPO_ROOT / "packaging" / "windows" / "MindedSetup.exe",
        REPO_ROOT / "MindedSetup.exe",
    ]

    for destination in destinations:
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(setup_exe, destination)
        print(f" -> Copied installer to: {destination}")

    # 6. Remove generated intermediate files only after the
    # setup executable has compiled and all copies have succeeded.
    if payload_zip.is_file():
        payload_zip.unlink()

    if release_info_cs.is_file():
        release_info_cs.unlink()

    print("\n[SUCCESS] INSTALLATION SETUP BUILD COMPLETE!")
    return setup_exe

if __name__ == "__main__":
    build_installer()
